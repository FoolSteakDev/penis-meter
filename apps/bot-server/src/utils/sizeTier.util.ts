function pickRandom<T>(items: T[]): T {
  return items[Math.floor(Math.random() * items.length)];
}

export function getSizeTierLabel(value: number): string {
  const tier = SIZE_TIERS.find((t) => value >= t.min) ?? SIZE_TIERS[SIZE_TIERS.length - 1];
  return pickRandom(tier.labels);
}
